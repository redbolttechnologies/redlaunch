(() => {
  const folderNameFromApplicationName = (name) =>
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "");

  const dialog = document.querySelector("#application-dialog");
  if (!dialog) {
    return;
  }

  const openButtons = document.querySelectorAll("[data-application-open]");
  const closeButtons = dialog.querySelectorAll("[data-application-close]");
  const nameInput = dialog.querySelector("#application-name");
  const folderNameInput = dialog.querySelector("#application-folder-name");
  const form = dialog.querySelector("form");
  const submitButton = dialog.querySelector("[data-application-submit]");
  let returnFocus = null;

  const setOpenButtonState = (expanded) => {
    openButtons.forEach((button) => {
      button.setAttribute("aria-expanded", expanded ? "true" : "false");
    });
  };

  const openDialog = (button) => {
    returnFocus = button;
    if (typeof dialog.showModal === "function") {
      if (!dialog.open) {
        dialog.showModal();
      }
    } else {
      dialog.setAttribute("open", "");
    }
    document.body.classList.add("dialog-open");
    setOpenButtonState(true);
    if (nameInput) {
      nameInput.focus();
    }
  };

  const closeDialog = () => {
    if (typeof dialog.close === "function" && dialog.open) {
      dialog.close();
    } else {
      dialog.removeAttribute("open");
    }
    document.body.classList.remove("dialog-open");
    setOpenButtonState(false);
    if (returnFocus) {
      returnFocus.focus();
    }
  };

  openButtons.forEach((button) => {
    button.addEventListener("click", () => openDialog(button));
  });
  closeButtons.forEach((button) => {
    button.addEventListener("click", closeDialog);
  });
  dialog.addEventListener("click", (event) => {
    if (event.target === dialog) {
      closeDialog();
    }
  });
  dialog.addEventListener("close", () => {
    document.body.classList.remove("dialog-open");
    setOpenButtonState(false);
    if (returnFocus) {
      returnFocus.focus();
    }
  });

  if (form && submitButton) {
    form.addEventListener("submit", () => {
      submitButton.disabled = true;
      submitButton.textContent = "Creating application…";
    });
  }

  if (nameInput && folderNameInput) {
    let folderNameAutoGenerated =
      !folderNameInput.value || folderNameInput.value === folderNameFromApplicationName(nameInput.value);

    nameInput.addEventListener("input", () => {
      if (folderNameAutoGenerated) {
        folderNameInput.value = folderNameFromApplicationName(nameInput.value);
      }
    });

    folderNameInput.addEventListener("input", () => {
      folderNameAutoGenerated = folderNameInput.value === folderNameFromApplicationName(nameInput.value);
    });
  }

  if (dialog.hasAttribute("open")) {
    dialog.removeAttribute("open");
    openDialog(null);
  }
})();
